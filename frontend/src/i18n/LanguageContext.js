const languageIndex = { en: 0, hi: 1, mr: 2 };

const LanguageContext = createContext(null);

function getNestedValue(source, path) {
  return path.split(".").reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : undefined), source);
}

function normalizeKey(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/_/g, " ")
    .replace(/\s+/g, " ");
}

function interpolate(template, params = {}) {
  return String(template).replace(/\{\{(\w+)\}\}/g, (_, key) => (params[key] !== undefined ? params[key] : ""));
}

function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(STORAGE_KEY) || "en");

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => {
    const t = (key, fallback = key, params) => {
      const template = getNestedValue(translations[language], key) || getNestedValue(translations.en, key) || fallback;
      return params ? interpolate(template, params) : template;
    };

    const tv = (category, rawValue, fallback = rawValue) => {
      const key = normalizeKey(rawValue);
      const entry = commonValues[category]?.[key];
      if (!entry) return fallback ?? rawValue;
      return entry[languageIndex[language] || 0] || entry[0];
    };

    return {
      language,
      setLanguage: (next) => {
        localStorage.setItem(STORAGE_KEY, next);
        setLanguageState(next);
      },
      t,
      tv,
      format: interpolate,
      languageOptions: [
        { value: "en", label: "English" },
        { value: "hi", label: "हिन्दी" },
        { value: "mr", label: "मराठी" },
      ],
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return context;
}

export { LanguageProvider, useLanguage };
